-- Куда вставлять: Supabase Dashboard → "SQL Editor" → "New query" →
-- вставить весь файл целиком → Run. Требует миграцию 010 (функция
-- note_search_text).
--
-- ВАЖНО: выполнить ДО того, как обновлённый сайт уйдёт на GitHub Pages —
-- адаптер начинает выбирать колонку body_empty, и без неё список заметок
-- у залогиненного пользователя не загрузится.
--
-- Зачем. Список заметок грузится без content (он бывает в мегабайтах из-за
-- фото в base64), поэтому клиент не мог понять, пуста ли заметка, пока её
-- не откроешь, — и крестик мгновенного удаления у пустых заметок появлялся
-- только после открытия. Теперь пустоту считает сервер, и в список приходит
-- готовый флаг.
--
-- Правило ЗЕРКАЛИТ isItemEmpty в src/modules/shared/panelSection.js:
-- пустая — если в тексте (без HTML) ничего нет, нет ни одного фото (<img>)
-- и ни одного штриха рисунка (<path>). Название не в счёт. Меняешь правило
-- здесь — меняй и там.
-- ============================================================

-- generated … stored: Postgres сам пересчитывает значение при каждой правке
-- content, а для уже существующих заметок посчитает его прямо сейчас.
-- note_search_text вызывается с пустым заголовком: нужен только текст тела,
-- она возвращает '' || '\n' || текст, поэтому \n обрезаем вместе с пробелами.
-- coalesce — на случай content = null: иначе всё выражение было бы null.
alter table public.notes
  add column body_empty boolean generated always as (
    btrim(public.note_search_text('', coalesce(content, '')), E' \n') = ''
    and coalesce(content, '') !~* '<img\M'
    and coalesce(content, '') !~* '<path\M'
  ) stored;
